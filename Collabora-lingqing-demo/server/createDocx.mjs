const STYLE_BY_TYPE = {
  heading1: 'Heading1',
  heading2: 'Heading2',
  paragraph: undefined,
}

export function createDocxFromTemplate(payload = {}) {
  const blocks = Array.isArray(payload.blocks) && payload.blocks.length
    ? payload.blocks
    : [{ type: 'heading1', text: payload.title || '未命名文档' }, { type: 'paragraph', text: '暂无正文，可直接在编辑器中编写，或使用右侧 AI 工具写入。' }]

  const paragraphs = blocks
    .map((block) => paragraphXml(block?.text ?? '', STYLE_BY_TYPE[block?.type] ?? undefined))
    .join('')

  const documentXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
  <w:body>
    ${paragraphs}
    <w:sectPr>
      <w:pgSz w:w="11906" w:h="16838"/>
      <w:pgMar w:top="1440" w:right="1440" w:bottom="1440" w:left="1440" w:header="720" w:footer="720"/>
    </w:sectPr>
  </w:body>
</w:document>`

  return createZip([
    { name: '[Content_Types].xml', data: CONTENT_TYPES },
    { name: '_rels/.rels', data: ROOT_RELS },
    { name: 'word/_rels/document.xml.rels', data: DOCUMENT_RELS },
    { name: 'word/styles.xml', data: STYLES },
    { name: 'word/document.xml', data: documentXml },
  ])
}
